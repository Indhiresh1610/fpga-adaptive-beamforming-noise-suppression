# Generates wiener_fd_tables.h : twiddle ROM (512-pt FFT) and periodic Hann window (scipy 'hann').
import math
N = 512
def arr(name, vals):
    s = f"static const float {name}[{len(vals)}] = {{\n"
    for i in range(0, len(vals), 4):
        s += "    " + ", ".join(f"{v:.9e}f" for v in vals[i:i+4]) + ",\n"
    return s + "};\n"
with open("wiener_fd_tables.h", "w") as f:
    f.write("// AUTO-GENERATED by gen_tables.py -- do not edit.\n#ifndef WIENER_FD_TABLES_H\n#define WIENER_FD_TABLES_H\n")
    f.write("// WFD_COS[k]=cos(2*pi*k/512), WFD_SIN[k]=sin(2*pi*k/512), k=0..255; twiddle W^k = COS - j*SIN\n")
    f.write(arr("WFD_COS", [math.cos(2*math.pi*k/N) for k in range(N//2)]))
    f.write(arr("WFD_SIN", [math.sin(2*math.pi*k/N) for k in range(N//2)]))
    f.write("// periodic Hann (scipy.signal.stft window='hann'): 0.5-0.5*cos(2*pi*n/512)\n")
    f.write(arr("WFD_HANN", [0.5-0.5*math.cos(2*math.pi*n/N) for n in range(N)]))
    f.write("#endif\n")
